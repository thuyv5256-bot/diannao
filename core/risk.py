# -*- coding: utf-8 -*-
"""
小满 · 风险事件模块

店主在进货前一天勾选"明天可能发生的风险"，小满把这种前瞻性信息纳入
补货计算 —— 这是规则 Agent 相对纯历史预测的关键增强：模型只能看到过去，
店主却知道明天会不会下暴雨、有没有临时节假日、供应商稳不稳。

四类风险，两类作用方向：
  · 需求侧：暴雨（分品类：冲动/易腐消费下降、囤货刚需上升）、高温（冷饮饮料需求↑）、
            节假日（全品类备货↑）→ 直接乘在销量预测上（forecast.py 落地）。
  · 供给侧：供应商断货 → 不改变预测，而是停止采购断供供应商的商品（policy.py 落地）。

风险因子与 seed_data.py 里"上帝视角"的真实冲击系数保持同向但不求一致：
店主的先验估计本来就不可能和真实世界精确相等，这本身就是合理的业务假设。
"""

# 风险键 → 界面标签 / 一句话说明
RISK_KEYS = ("rain", "heat", "holiday", "supplier")

RISK_LABELS = {
    "rain": "☔ 暴雨",
    "heat": "🔥 高温",
    "holiday": "📅 节假日",
    "supplier": "📦 供应商断货",
}

RISK_DESC = {
    "rain": "分品类：冷饮/水果/饮料客流下降，方便食品/粮油/日用品囤货上升",
    "heat": "冷饮饮料需求上升，上调销量预测",
    "holiday": "全品类备货需求上升，上调销量预测",
    "supplier": "供应商D可能断供，其名下商品本次不可采购",
}

# 暴雨对不同品类的需求方向不同（按 180 天真实经营数据估计，非"一刀切下调"）：
#   · 客流下降、冲动/易腐消费 → 下调：冷饮、水果、饮料、生鲜
#   · 囤货刚需 → 上调：方便食品、粮油、日用品（下雨天居民囤方便面/米面油/纸品）
# 数据不足的品类回退中性 1.0（既不无脑下调，也不强行上调）。
RAIN_FACTOR = {
    "冷饮": 0.70,      # 冲动消费，客流下降（真实 ≈0.74）
    "水果": 0.75,      # 易腐、客流下降（真实 ≈0.71）
    "饮料": 0.90,      # 小幅下降（真实 ≈0.94）
    "生鲜": 0.88,      # 小幅下降（真实 ≈0.90）
    "零食": 1.00,      # 基本中性（真实 ≈0.98）
    "方便食品": 1.30,  # 囤货上升（真实 ≈1.32）
    "粮油": 1.35,      # 囤货上升（真实 ≈1.37）
    "日用品": 1.30,    # 囤货上升（真实 ≈1.33）
}
RAIN_DEFAULT = 1.00    # 未知品类不盲目下调

# 高温对需求的拉动只作用于相关品类，不对全部 SKU 无差别抬升
HEAT_FACTOR = {"饮料": 1.30, "冷饮": 1.40}
HEAT_DEFAULT = 1.00    # 非相关品类保持中性

# 「供应商断货」事件对应的断供供应商（对应 products.supplier 字段）。
# 该供应商名下的商品本次视为「不可采购」，而不是简单加高安全库存。
SUPPLIER_OUTAGE_NAME = "供应商D"


def normalize(risks) -> list[str]:
    """把界面传来的任意形式（None / list / set）规整成有序风险键列表。"""
    if not risks:
        return []
    return [k for k in RISK_KEYS if k in risks]


def summary(active: list[str]) -> str:
    """给界面提醒区用的一句话总结（按固定顺序）。"""
    return "、".join(f"{RISK_LABELS[k]}（{RISK_DESC[k]}）" for k in active)
